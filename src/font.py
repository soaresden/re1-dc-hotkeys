def rows(ch):
    out = []
    for r in GLYPHS[ch]:
        b = 0
        for i, c in enumerate(r):
            if c == '#':
                b |= 0x80 >> i
        out.append(b)
    return out + [0]


def asm():
    lines = []
    for ch in CHARS:
        lines.append('        .byte ' + ', '.join('0x%02x' % b for b in rows(ch)) + "   /* '%s' */" % ch)
    return '\n'.join(lines) + '\n'


def encode(text):
    """string -> glyph indices (unknown characters become spaces)"""
    return [CHARS.index(c) if c in CHARS else 0 for c in text.upper()]


